import type { BenchRecord } from "@shared/bench";

export interface BenchHistoryPoint {
  receivedAtMs: number;
  temperatures: Record<string, number | null>;
  currentA: number | null;
  /** A line break, never an observed measurement. */
  gap: boolean;
}

/**
 * A bounded view of the actual USB buffer. Nulls preserve missing channels;
 * never carry the previous value forward or replace an invalid reading with 0.
 */
export function buildBenchHistory(records: readonly BenchRecord[]) {
  const recent = records.slice(-300);
  const latestIds = new Set<string>();
  for (let index = recent.length - 1; index >= 0 && latestIds.size < 5; index--) {
    for (const probe of recent[index].frame.temperatures) {
      if (latestIds.size < 5) latestIds.add(probe.id);
    }
  }
  const probeIds = Array.from(latestIds).sort();
  const emptyTemperatures = () => Object.fromEntries(
    probeIds.map(id => [id, null]),
  ) as Record<string, number | null>;
  const points: BenchHistoryPoint[] = [];
  let previous: BenchRecord | undefined;
  let temperatureCount = 0;
  let currentCount = 0;

  for (const record of recent) {
    const receivedAtMs = Date.parse(record.receivedAt);
    // These timestamps are generated by the USB hook, not supplied by firmware.
    if (!Number.isFinite(receivedAtMs)) {
      throw new Error("Bench history contains an invalid browser receipt timestamp.");
    }
    if (previous && (
      record.usbDataLossBefore ||
      receivedAtMs - Date.parse(previous.receivedAt) > 10_000 ||
      receivedAtMs < Date.parse(previous.receivedAt) ||
      record.frame.uptime_ms < previous.frame.uptime_ms ||
      record.frame.seq < previous.frame.seq
    )) {
      // Use the actual new frame's time; no synthetic measurement or timestamp.
      points.push({ receivedAtMs, temperatures: emptyTemperatures(), currentA: null, gap: true });
    }
    const temperatures = emptyTemperatures();
    for (const probe of record.frame.temperatures) {
      if (probeIds.includes(probe.id) && probe.c !== null && Number.isFinite(probe.c)) {
        temperatures[probe.id] = probe.c;
        temperatureCount++;
      }
    }
    const currentA = record.frame.current_status === "ok" &&
      record.frame.current_a !== null && Number.isFinite(record.frame.current_a)
      ? record.frame.current_a : null;
    if (currentA !== null) currentCount++;
    points.push({ receivedAtMs, temperatures, currentA, gap: false });
    previous = record;
  }

  return { probeIds, points, temperatureCount, currentCount, frameCount: recent.length };
}
